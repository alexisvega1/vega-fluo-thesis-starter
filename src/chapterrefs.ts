// Each chapter's own reference list, made from the thesis bibliography after a build.
// The entries are copied verbatim from the .bbl that BibTeX wrote, so they are formatted exactly as
// in the bibliography, and each keeps the number it has in the text ([4] here is [4] there).
// The lists live in .margin/chapter-refs/<chapter>.tex (outside the project tree, so they never show
// up as files, in word counts or in checks) and a chapter shows its list with one line under its
// \section{References}:  \input{.margin/chapter-refs/<chapter>}
import { mkdir } from "node:fs/promises";
import { basename, join } from "node:path";
import { citedKeys } from "./project";

export const REFS_DIR = ".margin/chapter-refs";
export const refsInput = (file: string) => `\\input{${REFS_DIR}/${basename(file).replace(/\.tex$/, "")}}`;
const HEAD = /^\s*\\section\*?\{\s*(References|Bibliography|Literature Cited)\s*\}/im;

export interface BblItem { n: number; label: string | null; body: string }

/** The entries of a BibTeX .bbl, by key, plus anything defined before the first entry. */
export function parseBbl(bbl: string): { preamble: string; items: Map<string, BblItem> } {
  const start = bbl.indexOf("\\begin{thebibliography}");
  const end = bbl.lastIndexOf("\\end{thebibliography}");
  const before = start < 0 ? "" : bbl.slice(0, start);
  const body = start < 0 ? "" : bbl.slice(bbl.indexOf("\n", start) + 1, end < 0 ? undefined : end);
  const items = new Map<string, BblItem>();
  const parts = body.split(/(?=\\bibitem\b)/);
  let n = 0;
  const pre: string[] = [];
  for (const part of parts) {
    const m = /^\\bibitem(?:\[([^\]]*)\])?\{([^}]*)\}\s*/.exec(part);
    if (!m) { if (part.trim()) pre.push(part.trim()); continue; }
    n++;
    items.set(m[2]!.trim(), { n, label: m[1] ?? null, body: part.slice(m[0].length).trim() });
  }
  return { preamble: [before.trim(), ...pre].filter(Boolean).join("\n"), items };
}

/** Keys cited in a chapter, ignoring commented-out text. */
export function chapterKeys(tex: string): string[] {
  const out: string[] = [];
  for (const line of tex.split("\n")) for (const k of citedKeys(line.replace(/(?<!\\)%.*$/, ""))) if (!out.includes(k)) out.push(k);
  return out;
}

/** True when the bibliography style gives author–year labels (natbib's "Author et~al.(2007)Full" form). */
export const authorYear = (bbl: ReturnType<typeof parseBbl>) => [...bbl.items.values()].some((it) => it.label !== null && /\(\d{4}[a-z]?\)/.test(it.label));

/**
 * The LaTeX for one chapter's list: a plain list, so there is no second BIBLIOGRAPHY heading and no key
 * is defined twice. Each entry carries a link target of its own (cite.<chapter>.<key>) so a citation in
 * the chapter can jump to it. Author–year styles get unlabelled, hanging-indent entries in bibliography
 * order (alphabetical); numeric styles keep their [n].
 */
export function renderList(keys: string[], bbl: ReturnType<typeof parseBbl>, chapter = ""): string {
  const rows = keys.map((k) => ({ k, it: bbl.items.get(k) })).filter((r) => r.it).sort((a, b) => a.it!.n - b.it!.n);
  const target = (k: string) => (chapter ? `\\hypertarget{cite.${chapter}.${k}}{}` : "");
  const head = "% Generated by Vega Fluo from the bibliography each time the PDF is built. Edits here are overwritten.\n";
  if (!rows.length) return head;
  return head + [
    "{\\sloppy\\clubpenalty4000\\widowpenalty4000",
    bbl.preamble,
    "\\providecommand{\\newblock}{}\\def\\newblock{\\hskip .11em plus .33em minus .07em}%",
    authorYear(bbl)
      ? "\\begin{list}{}{\\setlength{\\labelwidth}{0pt}\\setlength{\\leftmargin}{1.5em}\\setlength{\\itemindent}{-1.5em}\\setlength{\\labelsep}{0pt}\\setlength{\\itemsep}{0.5ex plus 0.2ex}\\setlength{\\parsep}{0pt}}"
      : "\\begin{list}{}{\\setlength{\\labelwidth}{2.6em}\\setlength{\\leftmargin}{3.3em}\\setlength{\\labelsep}{0.7em}\\setlength{\\itemsep}{0.5ex plus 0.2ex}\\setlength{\\parsep}{0pt}}",
    ...rows.map((r) => (authorYear(bbl) ? `\\item[] ${target(r.k)}${r.it!.body}` : `\\item[{[${r.it!.label ?? r.it!.n}]}] ${target(r.k)}${r.it!.body}`)),
    "\\end{list}}",
    "",
  ].filter((l) => l !== "").join("\n") + "\n";
}

export interface ChapterRefsResult { written: string[]; needInput: string[] }

/**
 * After a build: rewrite each chapter's list if it changed, and report chapters that have a
 * References section but do not yet show their list. Only files under .margin are written here.
 */
export async function updateChapterRefs(projectDir: string, chapters: { path: string; text: string }[], bblText: string): Promise<ChapterRefsResult> {
  const bbl = parseBbl(bblText);
  const out: ChapterRefsResult = { written: [], needInput: [] };
  await mkdir(join(projectDir, REFS_DIR), { recursive: true });
  const withList: string[] = [];
  for (const c of chapters) {
    if (!HEAD.test(c.text)) continue;
    const base = basename(c.path).replace(/\.tex$/, "");
    const file = join(projectDir, REFS_DIR, `${base}.tex`);
    const next = renderList(chapterKeys(c.text), bbl, base);
    if (c.text.includes(refsInput(c.path)) && next.includes("\\item")) withList.push(base);
    const prev = await Bun.file(file).text().catch(() => null);
    if (prev !== next) { await Bun.write(file, next); out.written.push(c.path); }
    if (!c.text.includes(refsInput(c.path))) out.needInput.push(c.path);
  }
  // which chapters show a list: citations in those link to it, others to the main bibliography
  const index = join(projectDir, REFS_DIR, "_index.tex");
  const idx = "% Generated by Vega Fluo: chapters whose citations link to their own reference list.\n" + withList.map((b) => `\\expandafter\\def\\csname vf@list@${b}\\endcsname{}`).join("\n") + "\n";
  if ((await Bun.file(index).text().catch(() => null)) !== idx) { await Bun.write(index, idx); out.written.push("_index"); }
  return out;
}

/**
 * Lines for the preamble (packages.tex) that make citations link to the chapter's own list when it has
 * one: natbib/hyperref's link start is pointed at cite.<file>.<key> instead of cite.<key>.
 */
export const LINK_HOOK = [
  "% --- Vega Fluo: citations link to the chapter's own reference list (generated in .margin/chapter-refs) ---",
  "\\RequirePackage{currfile}",
  "\\makeatletter",
  "\\InputIfFileExists{.margin/chapter-refs/_index.tex}{}{}",
  "\\AtBeginDocument{\\@ifundefined{hyper@natlinkstart}{}{%",
  "  \\let\\vf@natlinkstart\\hyper@natlinkstart",
  "  \\let\\vf@natlinkbreak\\hyper@natlinkbreak",
  "  \\def\\hyper@natlinkstart#1{\\ifcsname vf@list@\\currfilebase\\endcsname\\Hy@backout{#1}\\hyper@linkstart{cite}{cite.\\currfilebase.#1}\\def\\hyper@nat@current{#1}\\else\\vf@natlinkstart{#1}\\fi}%",
  "  \\def\\hyper@natlinkbreak#1#2{\\ifcsname vf@list@\\currfilebase\\endcsname\\hyper@linkend#1\\hyper@linkstart{cite}{cite.\\currfilebase.#2}\\else\\vf@natlinkbreak{#1}{#2}\\fi}}}",
  "\\setcitestyle{authoryear,round}",
  "\\makeatother",
  "% --- end Vega Fluo ---",
].join("\n");

/** Where the include line goes: right after the References heading (and its \label, if any). */
export function withRefsInput(text: string, file: string): string | null {
  if (text.includes(refsInput(file))) return null;
  const lines = text.split("\n");
  const i = lines.findIndex((l) => HEAD.test(l));
  if (i < 0) return null;
  const at = /^\s*\\label\{/.test(lines[i + 1] ?? "") ? i + 2 : i + 1;
  lines.splice(at, 0, refsInput(file));
  return lines.join("\n");
}

/** Make sure every list a chapter already includes exists, so a missing file can never break a build. */
export async function ensureStubs(projectDir: string, chapters: { path: string; text: string }[]) {
  for (const c of chapters) {
    if (!c.text.includes(refsInput(c.path))) continue;
    const file = join(projectDir, REFS_DIR, `${basename(c.path).replace(/\.tex$/, "")}.tex`);
    if (!(await Bun.file(file).exists())) { await mkdir(join(projectDir, REFS_DIR), { recursive: true }); await Bun.write(file, "% (empty until the next build)\n"); }
  }
}
